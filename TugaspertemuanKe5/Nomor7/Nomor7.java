package Pertemuan5PBO;

public class Nomor7 {
    public static void main(String[] args) {

        int a = 1;

        System.out.println("Menggunakan i++");

        while (a <= 5) {
            System.out.println(a++);
        }

        int b = 1;

        System.out.println("Menggunakan ++i");

        while (b <= 5) {
            System.out.println(++b);
        }
    }
}
